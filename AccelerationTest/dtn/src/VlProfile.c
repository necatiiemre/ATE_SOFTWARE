{
    for (uint8_t h = 0; h < profile->hm_count; h++)
        if (profile->hm[h].vl_id == vl_id)
            return VL_KIND_HM_TAP;

    if (profile->dtn_health_monitor && vl_id == DTN_HEALTH_MONITOR_VL)
        return VL_KIND_DTN_HM;

    for (uint8_t c = 0; c < profile->comm_count; c++) {
        const vl_run_t *run = &profile->comms[c];

        if (vl_id >= run->vl_first && vl_id < run->vl_first + run->vl_count)
            return VL_KIND_COMM;
    }

    for (uint8_t g = 0; g < profile->group_count; g++) {
        const vl_link_group_t *group = &profile->groups[g];
        const uint16_t span = (uint16_t)(group->link_count * group->vls_per_link);

        if (vl_id >= group->vl_base && vl_id < group->vl_base + span)
            return VL_KIND_FIBRE;
    }

    /* VL 4419-4490, whether or not this profile asked for them. */
    if (vl_id >= 4419 && vl_id <= 4490)
        return VL_KIND_MANAGEMENT;

    return VL_KIND_UNKNOWN;
}

const char *vl_profile_comm_label(const vl_profile_t *profile, uint16_t vl_id)
{
    for (uint8_t c = 0; c < profile->comm_count; c++) {
        const vl_run_t *run = &profile->comms[c];

        if (vl_id >= run->vl_first && vl_id < run->vl_first + run->vl_count)
            return run->label;
    }
    return NULL;
}

const vl_profile_t *vl_profile_all(size_t *count)
{
    if (count)
        *count = sizeof g_profiles / sizeof g_profiles[0];
    return g_profiles;
}

size_t vl_profile_enabled_count(const dtn_vl_t *records, size_t count)
{
    size_t enabled = 0;

    for (size_t i = 0; i < count; i++)
        if (dtn_vl_enabled(&records[i]))
            enabled++;
    return enabled;
}

int vl_profile_expand(const vl_profile_t *profile, dtn_vl_t *out, size_t cap)
{
    size_t n = 0;

    for (uint8_t g = 0; g < profile->group_count; g++) {
        const vl_link_group_t *group = &profile->groups[g];
        uint16_t vl = group->vl_base;

        for (uint8_t l = 0; l < group->link_count; l++)
            for (uint16_t k = 0; k < group->vls_per_link; k++) {
                if (n == cap)
                    return -1;
                dtn_vl_init(&out[n++], vl++, group->links[l].src,
                            1ull << group->links[l].dst);
            }
    }

    for (uint8_t h = 0; h < profile->hm_count; h++) {
        if (n == cap)
            return -1;
        dtn_vl_init(&out[n], profile->hm[h].vl_id, profile->hm[h].src_port,
                    1ull << profile->hm[h].dst_port);
        out[n].flags = profile->hm[h].flags;
        n++;
    }

    /* The DTN's own health monitor. The end-system block names the VL; without
     * a record for it the device has no way out to copper, and the capture's
     * 122 records do not carry one. Flag nibble 0xD is what the reference gives
     * this VL specifically - every other record, taps included, uses 0x9. */
    if (profile->dtn_health_monitor) {
        if (n == cap)
            return -1;
        dtn_vl_init(&out[n], DTN_HEALTH_MONITOR_VL, DTN_PORT_MANAGEMENT,
                    1ull << profile->dtn_hm_port);
        out[n].flags = FLAGS_NORMAL | DTN_VL_FLAG_PRIORITY;
        n++;
    }

    /* The copper legs, last. They are records the capture never had, so where
     * they sit in the table is ours to choose, and the end is the one place
     * that leaves everything before them where it was. */
    for (uint8_t c = 0; c < profile->comm_count; c++) {
        const vl_run_t *run = &profile->comms[c];

        for (uint16_t k = 0; k < run->vl_count; k++) {
            if (n == cap)
                return -1;
            dtn_vl_init(&out[n++], (uint16_t)(run->vl_first + k),
                        run->src_port, 1ull << run->dst_port);
        }
    }

    if (profile->management) {
        size_t mgmt_count;
        const dtn_vl_t *mgmt = vl_profile_management(&mgmt_count);

        if (n + mgmt_count > cap)
            return -1;
        memcpy(out + n, mgmt, mgmt_count * sizeof *mgmt);
        n += mgmt_count;
    }

    return (int)n;
}

/* Ports 0-31 carry fibre traffic; 32 and 33 are the copper end-system ports and
 * 34 is the DTN's internal management port. */
#define FIBRE_PORT_MASK      0x00000000FFFFFFFFull
#define COPPER_PORT_MASK     ((1ull << 32) | (1ull << 33))
#define MANAGEMENT_PORT_MASK (1ull << 34)

bool vl_profile_validate(const dtn_vl_t *records, size_t count,
                         char *reason, size_t reason_cap)
{
    uint64_t fibre_ports = 0, hm_tap_ports = 0;

    for (size_t i = 0; i < count; i++) {
        const dtn_vl_t *r = &records[i];

        if (r->vl_id < 3) {
            snprintf(reason, reason_cap,
                     "VL %u is in the reserved range 0-2", r->vl_id);
            return false;
        }
        /* The table is neither sorted nor contiguous, so a repeat can be
         * anywhere. 122 records make the quadratic scan free. */
        for (size_t k = 0; k < i; k++)
            if (records[k].vl_id == r->vl_id) {
                snprintf(reason, reason_cap, "VL %u appears twice", r->vl_id);
                return false;
            }
        if (!dtn_vl_enabled(r))
            continue;      /* a hole in the table; nothing else applies to it */

        if (r->dest_mask == 0) {
            snprintf(reason, reason_cap, "VL %u has no destination port", r->vl_id);
            return false;
        }

        /* The DTN's own management path shares port numbers with the fibre
         * links but none of their traffic, so it takes no part in this check -
         * whether it starts off-fibre or merely heads for the management
         * port, as VL 4420-4483 do from every fibre port. */
        if (!(1ull << r->src_port & FIBRE_PORT_MASK))
            continue;
        if (r->dest_mask & MANAGEMENT_PORT_MASK)
            continue;

        if (r->dest_mask & COPPER_PORT_MASK)
            hm_tap_ports |= 1ull << r->src_port;   /* a fibre-side HM tap */
        else
            fibre_ports |= (1ull << r->src_port) | (r->dest_mask & FIBRE_PORT_MASK);
    }

    uint64_t clash = fibre_ports & hm_tap_ports;
    if (clash) {
        for (int p = 0; p < DTN_PORT_COUNT; p++)
            if (clash >> p & 1) {
                snprintf(reason, reason_cap,
                         "port %d carries both fibre traffic and health monitor", p);
                return false;
            }
    }
    return true;
}
