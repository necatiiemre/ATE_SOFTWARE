size_t vl_profile_management_records(const uint8_t **raw)
{
    if (raw)
        *raw = REF_MGMT_RECORDS;
    return sizeof REF_MGMT_RECORDS / DTN_VL_RECORD_LEN;
}

const uint8_t *vl_profile_protocol_block(size_t *len)
{
    if (len)
        *len = sizeof REF_PROTOCOL_BLOCK;
    return REF_PROTOCOL_BLOCK;
}

const dtn_vl_t *vl_profile_management(size_t *count)
{
    static dtn_vl_t decoded[sizeof REF_MGMT_RECORDS / DTN_VL_RECORD_LEN];
    static bool ready;

    if (!ready) {
        for (size_t i = 0; i < sizeof decoded / sizeof decoded[0]; i++)
            dtn_vl_decode(REF_MGMT_RECORDS + i * DTN_VL_RECORD_LEN, &decoded[i]);
        ready = true;
    }
    if (count)
        *count = sizeof decoded / sizeof decoded[0];
    return decoded;
}

